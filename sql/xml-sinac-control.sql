-- Control de XMLs SINAC (SINAQ) — ejecutar en el SQL Editor de Supabase.
-- Idempotente: se puede re-ejecutar sin perder datos.

create table if not exists public.xml_sinac (
  id uuid primary key default gen_random_uuid(),
  nombre_fichero text not null,
  tecnico_email text not null,
  tecnico_nombre text,
  fecha_generacion timestamptz not null default now(),
  fecha_desde date,
  fecha_hasta date,
  num_za integer not null default 0,
  num_analiticas integer not null default 0,
  estado text not null default 'generado'
    check (estado in ('generado', 'anulado', 'correcto', 'con_errores')),
  fecha_estado timestamptz,
  fichero_path text,
  notas text
);

create table if not exists public.xml_sinac_zonas (
  id bigint generated by default as identity primary key,
  xml_id uuid not null references public.xml_sinac(id) on delete cascade,
  zona_fk integer,
  zona_nombre text not null,
  fecha_desde date,
  fecha_hasta date,
  num_analiticas integer not null default 0
);

create index if not exists xml_sinac_fecha_gen_idx on public.xml_sinac (fecha_generacion desc);
create index if not exists xml_sinac_tecnico_idx on public.xml_sinac (tecnico_email);
create index if not exists xml_sinac_zonas_xml_idx on public.xml_sinac_zonas (xml_id);
create index if not exists xml_sinac_zonas_zona_idx on public.xml_sinac_zonas (zona_fk);

-- RLS: lectura/alta para la app; los cambios de estado solo del autor del XML
-- o de un administrador (cabecera X-User-Role: 99). Sin política de DELETE:
-- los registros no se borran nunca (los anulados quedan en el histórico).
alter table public.xml_sinac enable row level security;
alter table public.xml_sinac_zonas enable row level security;

drop policy if exists "xml_sinac lectura" on public.xml_sinac;
create policy "xml_sinac lectura" on public.xml_sinac
  for select to anon, authenticated using (true);

drop policy if exists "xml_sinac alta" on public.xml_sinac;
create policy "xml_sinac alta" on public.xml_sinac
  for insert to anon, authenticated with check (true);

drop policy if exists "xml_sinac cambios" on public.xml_sinac;
create policy "xml_sinac cambios" on public.xml_sinac
  for update to anon, authenticated
  using (
    lower(tecnico_email) = lower(coalesce(current_setting('request.headers', true)::json ->> 'x-user-email', ''))
    or coalesce(current_setting('request.headers', true)::json ->> 'x-user-role', '') = '99'
  );

drop policy if exists "xml_sinac_zonas lectura" on public.xml_sinac_zonas;
create policy "xml_sinac_zonas lectura" on public.xml_sinac_zonas
  for select to anon, authenticated using (true);

drop policy if exists "xml_sinac_zonas alta" on public.xml_sinac_zonas;
create policy "xml_sinac_zonas alta" on public.xml_sinac_zonas
  for insert to anon, authenticated with check (true);

-- Bucket privado para los ficheros XML (re-descarga desde el histórico)
insert into storage.buckets (id, name, public)
values ('xml-sinac', 'xml-sinac', false)
on conflict (id) do nothing;

drop policy if exists "xml-sinac subir" on storage.objects;
create policy "xml-sinac subir" on storage.objects
  for insert to anon, authenticated with check (bucket_id = 'xml-sinac');

drop policy if exists "xml-sinac leer" on storage.objects;
create policy "xml-sinac leer" on storage.objects
  for select to anon, authenticated using (bucket_id = 'xml-sinac');
